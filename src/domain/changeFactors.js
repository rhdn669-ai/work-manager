export const FACTOR_CATEGORIES = [...new Set(CHANGE_FACTORS.map((x) => x.c))];

// 구분 → 세부 변경요인 목록
export const factorsOf = (category) => [...new Set(CHANGE_FACTORS.filter((x) => x.c === category).map((x) => x.f))];

// 구분 + 변경요인 → 기본 영향도. 예시가 여럿이면 가장 높은 값을 쓴다(보수적 판단).
export function suggestImpact(category, factor) {
  const hit = CHANGE_FACTORS.filter((x) => x.c === category && x.f === factor && x.score);
  return hit.length ? Math.max(...hit.map((x) => x.score)) : null;
}
